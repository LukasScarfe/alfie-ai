"""Dump xy-bench's vector font to custom_components/alfie/frontend/alfie-font.json.

Rerun (stdlib only; XY is a checkout of xy-bench, or any dir holding the `xy` package):

    docker run --rm -v "$PWD:/repo" -v "XY:/xy:ro" -w /repo python:3.13-alpine \
        python tools/font_dump.py /xy custom_components/alfie/frontend/alfie-font.json

Strokes are Douglas-Peucker simplified (TOL cap heights). A stroke is {"c": closed, "p": [x, y, ...]}
with flat coordinates; a dot (xy's small heavy loop) is kept as {"d": [x, y]}.
"""
import json
import math
import sys

TOL = 0.002


def dp(pts, tol):
    """Douglas-Peucker on an open polyline, keeping both ends."""
    if len(pts) < 3:
        return list(pts)
    (ax, ay), (bx, by) = pts[0], pts[-1]
    dx, dy = bx - ax, by - ay
    n = math.hypot(dx, dy)
    best, bi = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        d = (math.hypot(px - ax, py - ay) if n < 1e-12
             else abs(dx * (ay - py) - (ax - px) * dy) / n)
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[:bi + 1], tol)[:-1] + dp(pts[bi:], tol)


def simplify(pts, closed, tol):
    if not closed:
        return dp(pts, tol)
    # Closed: split at the point farthest from the first, simplify both halves.
    k = max(range(len(pts)), key=lambda i: math.dist(pts[i], pts[0]))
    a = dp(pts[:k + 1], tol)
    b = dp(pts[k:] + [pts[0]], tol)
    return a[:-1] + b[:-1]


def main(xy_dir, out):
    sys.path.insert(0, xy_dir)
    from xy import font
    glyphs = {}
    for ch, (adv, strokes) in sorted(font.GLYPHS.items()):
        out_s = []
        for s in strokes:
            pts = [(round(x, 3), round(y, 3)) for x, y in s.points]
            if s.closed and s.weight >= font._DOT_WEIGHT:
                xs, ys = [p[0] for p in pts], [p[1] for p in pts]
                out_s.append({"d": [round((min(xs) + max(xs)) / 2, 3), round((min(ys) + max(ys)) / 2, 3)]})
                continue
            pts = simplify(pts, s.closed, TOL)
            out_s.append({"c": 1 if s.closed else 0, "p": [round(v, 3) for p in pts for v in p]})
        glyphs[ch] = {"w": round(adv, 3), "s": out_s}
    data = {
        "_comment": "Generated by tools/font_dump.py from xy-bench's xy/font.py (Lukas Scarfe), "
                    "Douglas-Peucker simplified. Glyph space: baseline y=0, cap height y=1. "
                    "Stroke {c: closed, p: [x,y,...]}; dot {d: [x,y]}.",
        "metrics": {"cap": 1.0, "x_height": font.X_HEIGHT, "descender": font.DESCENDER,
                    "tracking": font.TRACKING, "digit_w": font.DIGIT_W, "dot_r": font._DOT_R},
        "glyphs": glyphs,
    }
    with open(out, "w") as f:
        json.dump(data, f, separators=(",", ":"), ensure_ascii=False)
        f.write("\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
